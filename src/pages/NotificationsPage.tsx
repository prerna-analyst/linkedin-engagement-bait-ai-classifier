import React from 'react';
import {
  Bell,
  CheckCheck,
  Sparkles,
  TrendingDown,
  Trash2,
  ExternalLink,
  ShieldCheck,
  Clock,
} from 'lucide-react';
import { useNotifications } from '../context/NotificationContext.tsx';

interface NotificationsPageProps {
  navigate: (path: string) => void;
}

export const NotificationsPage: React.FC<NotificationsPageProps> = ({ navigate }) => {
  const { notifications, unreadCount, markAsRead, markAllAsRead } = useNotifications();

  return (
    <div className="min-h-screen bg-[#0B0D12] text-white py-8">
      <div className="max-w-4xl mx-auto px-4 sm:px-6 lg:px-8">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 mb-8">
          <div>
            <div className="flex items-center gap-2">
              <Bell className="w-6 h-6 text-[#FFD43B]" />
              <h1 className="text-2xl sm:text-3xl font-extrabold text-white">
                Notification Center
              </h1>
            </div>
            <p className="text-xs text-[#A0A8B8] mt-1">
              Real-time in-app alerts generated by PriceTrack's periodic price-checking engine.
            </p>
          </div>

          {unreadCount > 0 && (
            <button
              onClick={markAllAsRead}
              className="px-4 py-2 rounded-xl text-xs font-semibold bg-[#1C2230] hover:bg-[#283248] text-[#4F8CFF] border border-[#283042] flex items-center gap-1.5 cursor-pointer self-start sm:self-auto"
            >
              <CheckCheck className="w-4 h-4" /> Mark All as Read
            </button>
          )}
        </div>

        {notifications.length === 0 ? (
          <div className="bg-[#141821] border border-[#1C2230] rounded-3xl p-12 text-center">
            <Bell className="w-12 h-12 text-[#A0A8B8] mx-auto mb-3" />
            <h3 className="text-base font-bold text-white mb-1">No Notifications Yet</h3>
            <p className="text-xs text-[#A0A8B8] max-w-sm mx-auto mb-6">
              When a store drops their price below your target, you'll receive real-time notifications right here.
            </p>
            <button
              onClick={() => navigate('/explore')}
              className="px-5 py-2.5 rounded-xl text-xs font-bold bg-[#FFD43B] text-black hover:bg-[#ffe066] cursor-pointer"
            >
              Explore Products
            </button>
          </div>
        ) : (
          <div className="space-y-3">
            {notifications.map((item) => (
              <div
                key={item.id}
                onClick={() => {
                  markAsRead(item.id);
                  if (item.link) navigate(item.link);
                }}
                className={`p-5 rounded-2xl border transition shadow-lg cursor-pointer flex items-start justify-between gap-4 ${
                  item.isRead
                    ? 'bg-[#141821] border-[#1C2230] text-[#A0A8B8]'
                    : 'bg-[#1C2230] border-[#FFD43B]/40 text-white'
                } hover:border-[#FFD43B]`}
              >
                <div className="flex items-start gap-3.5">
                  <div
                    className={`w-10 h-10 rounded-xl flex items-center justify-center shrink-0 ${
                      item.type === 'target_reached'
                        ? 'bg-[#22C55E]/10 text-[#22C55E] border border-[#22C55E]/30'
                        : item.type === 'price_drop'
                        ? 'bg-[#FFD43B]/10 text-[#FFD43B] border border-[#FFD43B]/30'
                        : 'bg-[#4F8CFF]/10 text-[#4F8CFF] border border-[#4F8CFF]/30'
                    }`}
                  >
                    {item.type === 'target_reached' ? (
                      <Sparkles className="w-5 h-5" />
                    ) : item.type === 'price_drop' ? (
                      <TrendingDown className="w-5 h-5" />
                    ) : (
                      <Bell className="w-5 h-5" />
                    )}
                  </div>

                  <div>
                    <div className="flex items-center gap-2">
                      <h4 className="text-sm font-bold text-white">{item.title}</h4>
                      {!item.isRead && (
                        <span className="w-2 h-2 rounded-full bg-[#FFD43B]" />
                      )}
                    </div>
                    <p className="text-xs mt-1 leading-relaxed">{item.message}</p>
                    {item.priceDifference && (
                      <div className="mt-2 text-xs font-bold text-[#22C55E]">
                        Saved ₹{item.priceDifference.toLocaleString('en-IN')} below your alert threshold!
                      </div>
                    )}
                    <span className="text-[11px] text-[#64748B] block mt-2 flex items-center gap-1">
                      <Clock className="w-3 h-3" /> {new Date(item.createdAt).toLocaleString()}
                    </span>
                  </div>
                </div>

                {item.link && (
                  <span className="text-xs text-[#FFD43B] hover:underline font-bold shrink-0 flex items-center gap-1">
                    View Deal <ExternalLink className="w-3.5 h-3.5" />
                  </span>
                )}
              </div>
            ))}
          </div>
        )}
      </div>
    </div>
  );
};
