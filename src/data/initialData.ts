// Generate 90 days of realistic historical price records
export function generateInitialHistory(): PriceHistoryRecord[] {
  const records: PriceHistoryRecord[] = [];
  let recordId = 1;

  INITIAL_LISTINGS.forEach(listing => {
    const days = [90, 60, 45, 30, 21, 14, 7, 3, 1, 0];
    const basePrice = listing.currentPrice;

    days.forEach((dayOffset) => {
      const date = new Date(Date.now() - dayOffset * 24 * 60 * 60 * 1000);
      // Realistic variance over time (±8%)
      const variationFactor = 1 + (Math.sin(dayOffset * 0.4 + recordId) * 0.07);
      const price = dayOffset === 0 ? basePrice : Math.round((basePrice * variationFactor) / 10) * 10;

      records.push({
        id: `hist-${recordId++}`,
        productId: listing.productId,
        storeId: listing.storeId,
        storeName: listing.storeName,
        price,
        recordedAt: date.toISOString(),
        isVerified: listing.verificationStatus === 'VERIFIED_LIVE',
        notes: dayOffset === 0 ? 'Latest verified scan' : 'Scheduled periodic price tracking capture'
      });
    });
  });

  return records;
}

